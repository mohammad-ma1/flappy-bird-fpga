# Generates FlappyBird.qsf ( and FlappyBird.qpf if missing ) for the Flappy Bird project
# usage:  powershell -ExecutionPolicy Bypass -File tools\gen_qsf.ps1
# pin locations are read from Lab1Demo constraints/pin.tcl ( LED pins renamed to LEDR[0..9] )
# do NOT run pin.tcl on this project : the pins are already here , and pin.tcl turns OPTIMIZE_HOLD_TIMING off
# ( hold-time violations ) . if it was run , run this script again to restore a clean FlappyBird.qsf
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

$pins = @{}
foreach ($l in Get-Content constraints\pin.tcl) {
    if ($l -match '^\s*set_location_assignment\s+(PIN_\w+)\s+-to\s+(\S+)') { $pins[$matches[2]] = $matches[1] }
}
# Lab1Demo LED names -> LEDR
$ledFrom = @('ball_toggle','ir_write','sound_on','LEDR[3]','LEDR[4]','numKey[0]','numKey[1]','numKey[2]','numKey[3]','AUDOUT[0]')
for ($i = 0; $i -lt 10; $i++) { $pins["LEDR[$i]"] = $pins[$ledFrom[$i]] }

$want = @('CLOCK_50','resetN_pin','KEY[1]','KEY[2]','KEY[3]') +
        (0..9 | ForEach-Object { "SW[$_]" }) +
        (0..9 | ForEach-Object { "LEDR[$_]" }) +
        (0..5 | ForEach-Object { $h = $_; 0..6 | ForEach-Object { "HEX$h[$_]" } }) +
        (0..28 | ForEach-Object { "OVGA[$_]" }) +
        @('AUDIN[1]','AUDIN[2]','AUDOUT[4]','AUDOUT[5]','AUDOUT[6]','AUDOUT[7]','PS2_CLK','PS2_DAT')

$q = New-Object System.Collections.Generic.List[string]
$q.Add('# Flappy Bird (Controlled Maze) - Lab 1A 044157 - Quartus Prime 17.0 Lite')
$q.Add('# generated by tools\gen_qsf.ps1 - pin locations from Lab1Demo constraints/pin.tcl ( LED pins renamed to LEDR[0..9] )')
foreach ($a in @('FAMILY "Cyclone V"', 'DEVICE 5CSXFC6D6F31C6', 'TOP_LEVEL_ENTITY TOP_FLAPPY', 'ORIGINAL_QUARTUS_VERSION 17.0.0',
                 'LAST_QUARTUS_VERSION "17.0.0 Lite Edition"', 'PROJECT_OUTPUT_DIRECTORY output_files', 'NUM_PARALLEL_PROCESSORS ALL',
                 'MESSAGE_DISABLE 292013', 'MESSAGE_DISABLE 12240', 'FITTER_EFFORT "AUTO FIT"',
                 'OPTIMIZE_HOLD_TIMING "ALL PATHS"')) {
    $q.Add("set_global_assignment -name $a")
}
$q.Add('')
$q.Add('# ---- Lab1Demo files ( unchanged )')
foreach ($f in @('QXP_FILE audio_codec_controller.QXP', 'QXP_FILE KBDINTF.qxp', 'QIP_FILE CLK_31P5.qip', 'SIP_FILE CLK_31P5.sip',
                 'SYSTEMVERILOG_FILE RTL/VGA/VGA_Controller.sv', 'SYSTEMVERILOG_FILE RTL/VGA/square_object.sv', 'BDF_FILE RTL/KEYBOARDX/TOP_KBD.bdf', 'SYSTEMVERILOG_FILE RTL/KEYBOARDX/keyPad_decoder.sv',
                 'BDF_FILE RTL/AUDIO/AUDIO.bdf', 'SYSTEMVERILOG_FILE RTL/AUDIO/ToneDecoder.sv', 'SYSTEMVERILOG_FILE RTL/AUDIO/SinTable.sv',
                 'SYSTEMVERILOG_FILE RTL/AUDIO/prescaler.sv', 'SYSTEMVERILOG_FILE RTL/AUDIO/Mili_sec_counter.sv',
                 'SYSTEMVERILOG_FILE RTL/AUDIO/melody_player_1.sv', 'SYSTEMVERILOG_FILE RTL/AUDIO/addr_counter.sv',
                 'SYSTEMVERILOG_FILE RTL/Seg7/SEG7.SV')) {
    $q.Add("set_global_assignment -name $f")
}
$q.Add('')
$q.Add('# ---- Flappy Bird files')
Get-ChildItem RTL\FLAPPY\*.sv | Sort-Object Name | ForEach-Object { $q.Add("set_global_assignment -name SYSTEMVERILOG_FILE RTL/FLAPPY/$($_.Name)") }
$q.Add('set_global_assignment -name SYSTEMVERILOG_FILE RTL/TOP/TOP_FLAPPY.sv')
$q.Add('set_global_assignment -name SDC_FILE constraints/flappy.sdc')
$q.Add('set_global_assignment -name TCL_SCRIPT_FILE constraints/flappy_pins.tcl')
$q.Add('')
$q.Add('# ---- pins')
foreach ($p in $want) {
    if (-not $pins.ContainsKey($p) -or -not $pins[$p]) { throw "no pin location for $p in pin.tcl" }
    $q.Add("set_location_assignment $($pins[$p]) -to $p")
}
$q.Add('')
$q.Add('# ---- all pins 3.3-V LVTTL ( as pin.tcl does )')
foreach ($p in $want) { $q.Add("set_instance_assignment -name IO_STANDARD `"3.3-V LVTTL`" -to $p") }

$utf8 = New-Object Text.UTF8Encoding $false
[IO.File]::WriteAllText("$root\FlappyBird.qsf", ($q -join "`r`n") + "`r`n", $utf8)
if (-not (Test-Path "$root\FlappyBird.qpf")) {
    [IO.File]::WriteAllText("$root\FlappyBird.qpf", "QUARTUS_VERSION = `"17.0`"`r`n`r`n# Revisions`r`n`r`nPROJECT_REVISION = `"FlappyBird`"`r`n", $utf8)
}

# the same pins as a Tcl script ( safe to run : it does not touch OPTIMIZE_HOLD_TIMING like pin.tcl )
$t = New-Object System.Collections.Generic.List[string]
$t.Add('# Flappy Bird (Controlled Maze) - Lab 1A 044157')
$t.Add('# flappy_pins.tcl : the pins of the project ( DE10-Standard ) - the same assignments that are in FlappyBird.qsf')
$t.Add('#   the pin locations come from the course file constraints/pin.tcl ( Lab1Demo ) , with the port names of TOP_FLAPPY')
$t.Add('#   ( the Lab1Demo LED names are renamed to LEDR[0..9] ) . all the pins are 3.3-V LVTTL .')
$t.Add('#   unlike pin.tcl , this file does not change OPTIMIZE_HOLD_TIMING , so it is safe to run :')
$t.Add('#   Quartus : Tools -> Tcl Scripts -> flappy_pins.tcl -> Run   ( or : quartus_sh -t constraints/flappy_pins.tcl )')
$t.Add('# generated by tools\gen_qsf.ps1')
$t.Add('')
$t.Add('package require ::quartus::project')
$t.Add('')
$t.Add('# open the project if this script runs alone ( quartus_sh -t ) ; in the Quartus GUI it is already open')
$t.Add('set opened 0')
$t.Add('if {![is_project_open]} {')
$t.Add("`tproject_open FlappyBird")
$t.Add("`tset opened 1")
$t.Add('}')
$t.Add('')
$t.Add("# ---- pin locations ( $($want.Count) pins )")
foreach ($p in $want) { $t.Add("set_location_assignment $($pins[$p]) -to $p") }
$t.Add('')
$t.Add('# ---- all pins 3.3-V LVTTL')
foreach ($p in $want) { $t.Add("set_instance_assignment -name IO_STANDARD `"3.3-V LVTTL`" -to $p") }
$t.Add('')
$t.Add('# save the assignments in FlappyBird.qsf')
$t.Add('export_assignments')
$t.Add('if {$opened} { project_close }')
[IO.File]::WriteAllText("$root\constraints\flappy_pins.tcl", ($t -join "`r`n") + "`r`n", $utf8)

Write-Host "FlappyBird.qsf : $($want.Count) pins"
